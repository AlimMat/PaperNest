const { chromium } = require(process.env.EZREAD_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
(async () => {
  const origin = process.env.EZREAD_TEST_URL;
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const group = name => page.locator('.collection-nav').filter({ has: page.locator('.collection-label', { hasText: new RegExp(`^${name}$`) }) });
  const ready = () => page.waitForFunction(() => !state.collectionBusy && !document.querySelector('#collection-dialog').open);
  const read = async () => (await page.request.get(origin + '/api/papers')).json();
  try {
    await page.goto(origin); await page.waitForFunction(() => !state.loading);
    assert.equal(await page.locator('#collection-rename').isDisabled(), true);
    assert.equal(await page.locator('#collection-up').isDisabled(), true);
    const groupNames = () => page.locator('.collection-label').allTextContents();
    assert.deepEqual(await groupNames(), ['Agent', 'RL', 'VLA']);
    await group('RL').click();
    await page.locator('#collection-up').click(); await ready();
    assert.deepEqual(await groupNames(), ['RL', 'Agent', 'VLA']);
    assert.equal(await page.locator('#collection-up').isDisabled(), true);
    await page.reload(); await page.waitForFunction(() => !state.loading);
    assert.deepEqual(await groupNames(), ['RL', 'Agent', 'VLA']);
    await group('RL').click();
    await page.locator('#collection-down').click(); await ready();
    assert.deepEqual(await groupNames(), ['Agent', 'RL', 'VLA']);
    await group('VLA').click();
    assert.equal(await page.locator('#collection-rename').isDisabled(), false);
    await page.locator('#collection-rename').click();
    assert.equal(await page.locator('#collection-name').inputValue(), 'VLA');
    await page.locator('#collection-name').fill('Robotics');
    await page.locator('#collection-confirm').click(); await ready();
    assert.equal(await group('VLA').count(), 0);
    assert.equal(await group('Robotics').getAttribute('aria-pressed'), 'true');
    assert.deepEqual((await read()).papers[0].collections, ['Robotics', 'Agent']);
    await page.locator('#collection-rename').click();
    await page.locator('#collection-name').fill('Agent');
    await page.locator('#collection-confirm').click();
    await page.getByText('这个分组名称已经存在，请使用其他名称。', { exact: true }).waitFor();
    assert.equal(await page.locator('#collection-dialog').evaluate(node => node.open), true);
    await page.locator('#collection-dialog [data-close]').first().click();
    await page.locator('#collection-remove').click();
    assert.equal(await page.locator('#collection-name').isVisible(), false);
    await page.locator('#collection-dialog [data-close]').first().click();
    assert.equal(await group('Robotics').count(), 1, 'Cancel keeps the group');
    await page.locator('#collection-remove').click();
    await page.locator('#collection-confirm').click(); await ready();
    const result = await read();
    assert.equal(result.papers.length, 3);
    assert.deepEqual(result.papers.map(p => p.collections), [['Agent'], [], ['RL']]);
    assert.equal(await group('Robotics').count(), 0);
    await page.locator('[data-view="uncategorized"]').click();
    assert.equal(await page.locator('.paper-card').count(), 1);
    await page.locator('#new-collection').click();
    await page.locator('#collection-name').fill('Empty');
    await page.locator('#collection-confirm').click(); await ready();
    await page.locator('#collection-rename').click();
    await page.locator('#collection-name').fill('Empty renamed');
    await page.locator('#collection-confirm').click(); await ready();
    await page.reload(); await page.waitForFunction(() => !state.loading);
    assert.equal(await group('Empty renamed').count(), 1);
    await group('Empty renamed').click();
    await page.locator('#collection-remove').click();
    await page.locator('#collection-confirm').click(); await ready();
    await group('Agent').click();
    // Long group lists scroll independently while all surrounding controls stay fixed.
    await page.evaluate(async () => {
      await api('/api/settings', { method: 'PATCH', body: { collections: Array.from({ length: 25 }, (_, index) => `Group ${index + 1}`) } });
      await loadLibrary();
    });
    const fixedSelectors = ['.brand', '.workspace-tabs', '#search', '#main-nav', '#import-top', '.collection-heading', '.collection-tools', '#settings-button'];
    const positions = () => page.evaluate(selectors => selectors.map(selector => document.querySelector(selector).getBoundingClientRect().top), fixedSelectors);
    const beforeScroll = await positions();
    await page.locator('#collections-nav').hover();
    await page.mouse.wheel(0, 550);
    await page.waitForFunction(() => document.querySelector('#collections-nav').scrollTop > 100);
    assert.deepEqual(await positions(), beforeScroll);
    assert.equal(await page.locator('#reading-sidebar').evaluate(node => node.scrollTop), 0);
    const output = path.join(process.env.EZREAD_TEST_ROOT, 'work/collection-verification'); fs.mkdirSync(output, { recursive: true });
    await page.screenshot({ path: path.join(output, 'groups-wide.png') });
    await page.setViewportSize({ width: 1000, height: 720 });
    await page.locator('#collections-nav').evaluate(node => { node.scrollTop = 0; });
    const narrowBefore = await positions();
    await page.locator('#collections-nav').hover(); await page.mouse.wheel(0, 450);
    await page.waitForFunction(() => document.querySelector('#collections-nav').scrollTop > 100);
    assert.deepEqual(await positions(), narrowBefore);
    await page.screenshot({ path: path.join(output, 'groups-narrow.png') });
    assert.ok(await page.locator('#collection-remove').evaluate(node => node.getBoundingClientRect().right <= innerWidth));
    const unsafe = await page.request.post(origin + '/api/collections', { headers: { Origin: 'https://example.invalid' }, data: { operation: 'remove', name: 'Agent' } });
    assert.equal(unsafe.status(), 403);
    const invalid = await page.request.post(origin + '/api/collections', { data: { operation: 'rename', name: 'Agent', new_name: '' } });
    assert.equal(invalid.status(), 400);
    assert.deepEqual(errors, []);
    console.log('Group browser checks passed: rename, remove/cancel, duplicates, empty groups, reload, multiple memberships, uncategorized, layout and Origin checks.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
