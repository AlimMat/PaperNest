const { chromium } = require(process.env.EZREAD_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const origin = process.env.EZREAD_TEST_URL;
(async () => {
  const browser = await chromium.launch({ headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe' });
  const page = await browser.newPage({ viewport: { width: 1500, height: 1000 } });
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const output = path.join(process.env.EZREAD_TEST_ROOT, 'work/writing-verification');
  fs.mkdirSync(output, { recursive: true });
  const compiled = async () => {
    await page.waitForFunction(() => writingState.doc?.latexPreview && !writingState.doc.latexPreview.pending, null, { timeout: 100000 });
    const error = await page.locator('#writing-latex-error').innerText();
    assert.equal(error, '');
    await page.waitForFunction(() => document.querySelector('#writing-latex-pages img')?.naturalWidth > 1000);
  };
  async function create(name, language) {
    await page.locator('#writing-new').click();
    await page.locator('#writing-name').fill(name);
    await page.locator('#writing-format-trigger').click();
    await page.locator('#writing-format-menu [data-value="tex"]').click();
    assert.equal(await page.locator('#writing-latex-language-field').isVisible(), true);
    await page.locator('#writing-latex-language-trigger').click();
    await page.locator(`#writing-latex-language-menu [data-value="${language}"]`).click();
    await page.locator('#writing-confirm').click();
    await page.waitForFunction(() => !writingState.busy && !document.querySelector('#writing-dialog').open);
  }
  try {
    await page.goto(origin);
    await page.waitForFunction(() => !state.loading);
    await page.locator('#mode-writing').click();
    await create('中文排版验收', 'zh');
    assert.match(await page.locator('#writing-source').inputValue(), /ctexart/);
    await page.locator('#writing-preview-toggle').click();
    await compiled();
    assert.equal(await page.locator('#writing-source').isVisible(), true);
    const pageWidth = await page.locator('#writing-latex-pages img').first().evaluate(node => node.getBoundingClientRect().width);
    const zoomToken = await page.evaluate(() => writingState.doc.latexPreview.token);
    await page.locator('#writing-zoom-in').click();
    const zoomWidth = await page.locator('#writing-latex-pages img').first().evaluate(node => node.getBoundingClientRect().width);
    assert.ok(Math.abs(zoomWidth / pageWidth - 1.1) < .01, JSON.stringify({ pageWidth, zoomWidth }));
    assert.equal(await page.evaluate(() => writingState.doc.latexPreview.token), zoomToken, 'Zoom does not recompile the PDF');
    await page.locator('#writing-zoom-out').click();
    await page.screenshot({ path: path.join(output, 'latex-chinese-preview.png') });
    let token = await page.evaluate(() => writingState.doc.latexPreview.token);
    const pdf = await page.request.get(origin + `/api/writing/latex/${token}/document.pdf`);
    assert.equal(pdf.status(), 200);
    fs.writeFileSync(path.join(output, 'latex-chinese.pdf'), await pdf.body());
    await page.locator('#writing-read-toggle').click();
    await page.waitForFunction(() => writingLatex.reading && !writingState.busy);
    assert.equal(await page.locator('#writing-source').isVisible(), false);
    assert.equal(await page.locator('#writing-format-tools').isVisible(), false);
    assert.equal(await page.locator('#writing-latex-preview').isVisible(), true);
    assert.equal(await page.locator('.writing-heading').isVisible(), false);
    assert.equal(await page.locator('.writing-status').isVisible(), false);
    assert.equal(await page.locator('.writing-latex-bar').isVisible(), false);
    assert.deepEqual(await page.locator('.writing-save-tools button:visible').allTextContents(), ['− 缩小', '+ 放大', '打开阅读', '退出阅读']);
    assert.ok(await page.locator('#writing-latex-preview').evaluate(node => node.getBoundingClientRect().top < 65));
    await page.screenshot({ path: path.join(output, 'latex-chinese-reading.png') });
    await page.locator('#writing-read-toggle').click();
    await page.waitForFunction(() => !writingLatex.reading && !writingState.busy);
    assert.equal(await page.locator('.writing-heading').isVisible(), true);
    assert.equal(await page.locator('.writing-latex-bar').isVisible(), true);
    assert.equal(await page.locator('.writing-status').isVisible(), true);
    const original = await page.locator('#writing-source').inputValue();
    await page.locator('#writing-source').fill(original.replace('在这里开始写作。', '内容已经更新。\\newpage 第二页测试。'));
    assert.match(await page.locator('#writing-latex-status').innerText(), /内容已更改/);
    await page.locator('#writing-latex-compile').click();
    await compiled();
    assert.equal(await page.locator('#writing-latex-pages img').count(), 2);
    token = await page.evaluate(() => writingState.doc.latexPreview.token);
    await page.locator('#writing-source').fill('\\documentclass{article}\n\\begin{document}\n\\unknowncommand\n\\end{document}');
    await page.locator('#writing-latex-compile').click();
    await page.locator('#writing-latex-error').waitFor({ state: 'visible', timeout: 90000 });
    assert.match(await page.locator('#writing-latex-error').innerText(), /编译失败/);
    assert.equal(await page.evaluate(() => writingState.doc.latexPreview.token), token);
    assert.match(await page.locator('#writing-source').inputValue(), /unknowncommand/);
    await page.locator('#writing-source').fill(original); await page.evaluate(() => writingFlush());
    await create('English layout', 'en');
    await compiled();
    const english = await page.locator('#writing-source').inputValue();
    assert.match(english, /\{article\}/); assert.match(english, /Introduction/);
    assert.ok(await page.locator('.writing-save-tools button:visible, #writing-format-tools button:visible').count() <= 12, 'LaTeX toolbar has at most twelve visible controls');
    await page.locator('#writing-latex-layout-trigger').click();
    await page.locator('#writing-latex-layout-menu').getByRole('option', { name: '中文排版', exact: true }).click();
    assert.match(await page.locator('#writing-source').inputValue(), /ctexart/);
    assert.match(await page.locator('#writing-source').inputValue(), /Start writing here/);
    await page.locator('#writing-latex-layout-trigger').click();
    await page.locator('#writing-latex-layout-menu').getByRole('option', { name: '英文排版', exact: true }).click();
    assert.match(await page.locator('#writing-source').inputValue(), /\{article\}/);
    await page.locator('#writing-latex-compile').click(); await compiled();
    await page.screenshot({ path: path.join(output, 'latex-english-preview.png') });
    token = await page.evaluate(() => writingState.doc.latexPreview.token);
    fs.writeFileSync(path.join(output, 'latex-english.pdf'), await (await page.request.get(origin + `/api/writing/latex/${token}/document.pdf`)).body());
    // Late compile results cannot replace a different manuscript's preview.
    let release;
    await page.route('**/api/writing/latex-preview', async route => {
      await new Promise(resolve => { release = resolve; }); await route.continue();
    });
    await page.locator('#writing-latex-compile').click();
    await page.waitForFunction(() => writingState.doc.latexPreview.pending);
    while (!release) await new Promise(resolve => setTimeout(resolve, 20));
    await page.evaluate(() => writingOpen('增强写作.md')); release();
    await page.waitForTimeout(6000);
    assert.equal(await page.locator('#writing-latex-preview').isVisible(), false);
    assert.equal(await page.locator('#writing-preview').isVisible(), true);
    await page.unroute('**/api/writing/latex-preview');
    await page.evaluate(() => writingOpen('English layout.tex')); await compiled();
    await page.setViewportSize({ width: 1000, height: 720 });
    await page.locator('#writing-read-toggle').click();
    await page.waitForFunction(() => writingLatex.reading && !writingState.busy);
    await page.evaluate(() => { state.settings.theme = 'graphite'; state.settings.ui_font_size = 20; applyPreferences(); });
    await page.waitForTimeout(300); // Let theme color transitions finish before visual QA.
    await page.screenshot({ path: path.join(output, 'latex-reading-narrow.png') });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth + 1), false);
    assert.equal(await page.locator('#writing-source').isVisible(), false);
    assert.deepEqual(errors, []);
    console.log('LaTeX passed: Chinese/English templates, actual XeLaTeX/PDF, split/read, source-preserving language switch, multipage, error/recovery, stale status, cross-document race, download and narrow layout.');
  } finally { await browser.close(); }
})().catch(error => { console.error(error); process.exitCode = 1; });
