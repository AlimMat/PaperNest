const { chromium } = require(process.env.EZREAD_PLAYWRIGHT || 'playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const fs = require('node:fs');
const origin = process.env.EZREAD_TEST_URL;
(async () => {
  const browser = await chromium.launch({headless: true, executablePath: 'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe'});
  const page = await browser.newPage({viewport: {width: 1600, height: 1000}});
  const errors = []; page.on('pageerror', error => errors.push(error.message));
  const output = path.join(process.env.EZREAD_TEST_ROOT, 'work/readwrite-verification'); fs.mkdirSync(output, {recursive: true});
  const split = () => page.waitForFunction(() => readwrite.active && !readwrite.switching);
  const saved = () => page.waitForFunction(() => writingState.doc.content === writingState.doc.saved && !writingState.busy);
  try {
    await page.goto(origin); await page.waitForFunction(() => !state.loading);
    await page.locator('#mode-writing').click();
    await page.locator('.writing-tree-item[data-path="读写草稿.md"]').click();
    await page.waitForFunction(() => !writingState.busy && writingState.doc?.path === '读写草稿.md');
    await page.evaluate(() => { writingMarkdown.editor.setValue('# 研究记录\n\n边阅读论文，边记录研究思路。'); window.keptEditor = writingMarkdown.editor; window.keptDoc = writingMarkdown.editor.getDoc(); });
    await page.locator('#writing-open-reading').click();
    await page.locator('#readwrite-picker-list button').filter({hasText: 'PDF selection fixture'}).click();
    await split();
    await page.waitForFunction(() => document.querySelector('#original-scroll img')?.naturalWidth > 100);
    assert.equal(await page.locator('#writing-view').isVisible(), true);
    assert.equal(await page.locator('#original-scroll').isVisible(), true);
    assert.equal(await page.evaluate(() => writingMarkdown.editor === window.keptEditor && writingMarkdown.editor.getDoc() === window.keptDoc), true);
    await page.locator('.CodeMirror textarea').focus();
    await page.keyboard.press('Control+End'); await page.keyboard.insertText('\n新的分析内容');
    await page.keyboard.press('Control+s'); await saved();
    await page.evaluate(() => setReaderPage(2));
    await page.waitForFunction(() => state.readerPage === 2);
    await page.screenshot({path: path.join(output, 'readwrite-wide.png')});
    const bounds = await page.evaluate(() => ({left: document.querySelector('#reader-content').getBoundingClientRect().right, right: document.querySelector('#readwrite-writing').getBoundingClientRect().left}));
    assert.ok(bounds.left <= bounds.right);
    await page.locator('#writing-read-toggle').click();
    await page.waitForFunction(() => writingMarkdown.reading && !writingState.busy);
    assert.equal(await page.locator('.writing-heading').isVisible(), false);
    assert.deepEqual(await page.locator('.writing-toolbar button:visible').allTextContents(), ['退出阅读']);
    assert.equal(await page.locator('#original-scroll').isVisible(), true);
    assert.equal(await page.locator('#writing-preview').isVisible(), true);
    await page.locator('#writing-read-toggle').click();
    await page.waitForFunction(() => !writingMarkdown.reading && !writingState.busy);
    assert.equal(await page.locator('.writing-heading').isVisible(), true);
    assert.equal(await page.evaluate(() => writingMarkdown.editor.getDoc() === window.keptDoc), true);
    const divider = page.locator('#readwrite-divider'); const box = await divider.boundingBox();
    await page.mouse.move(box.x + 5, box.y + 150); await page.mouse.down(); await page.mouse.move(box.x + 130, box.y + 150); await page.mouse.up();
    assert.ok(await page.evaluate(() => readwrite.ratio > .55));
    await divider.focus(); await page.keyboard.press('Home');
    assert.equal(await page.evaluate(() => readwrite.ratio), .5);
    // A second modal (settings) does not discard either panel.
    await page.locator('#reader-content').getByRole('button', {name: '设置', exact: true}).click();
    await page.locator('#settings-dialog').waitFor({state: 'visible'});
    await page.keyboard.press('Escape'); await split();
    await page.locator('#reader-notes-toggle').click();
    await page.locator('#reader-notes-text').fill('双栏中记录的论文笔记');
    await page.locator('.CodeMirror textarea').focus();
    await page.evaluate(() => readerSaveNotes());
    assert.equal(await page.locator('#reader-notes-text').inputValue(), '双栏中记录的论文笔记');
    await page.locator('#reader-notes-toggle').click();
    // A failed manuscript save must not silently collapse or lose the editor.
    await page.route('**/api/writing', route => route.request().method() === 'POST'
      ? route.fulfill({status: 503, contentType: 'application/json', body: '{"error":"offline check"}'}) : route.continue());
    await page.evaluate(() => writingMarkdown.editor.replaceRange('\n离线草稿', writingMarkdown.editor.posFromIndex(writingMarkdown.editor.getValue().length)));
    await page.locator('#readwrite-only-reading').click();
    await page.locator('#writing-recovery').waitFor({state: 'visible'});
    assert.equal(await page.evaluate(() => readwrite.active), true);
    await page.unroute('**/api/writing'); await page.evaluate(() => writingFlush());
    await page.locator('#readwrite-only-reading').click();
    await page.waitForFunction(() => !readwrite.active);
    assert.equal(await page.locator('#original-scroll').isVisible(), true);
    await page.locator('#reader-open-writing').click(); await split();
    assert.equal(await page.evaluate(() => writingMarkdown.editor.getDoc() === window.keptDoc), true);
    assert.match(await page.evaluate(() => writingMarkdown.editor.getValue()), /新的分析内容/);
    // Switching papers keeps the editor intact and saves the old paper position.
    await page.locator('.reader-back').click();
    await page.locator('#readwrite-search').fill('Second reference');
    await page.locator('#readwrite-picker-list button').click(); await split();
    assert.equal(await page.evaluate(() => state.reader.id), 'abcdef1234567890');
    assert.equal(await page.evaluate(() => writingMarkdown.editor.getDoc() === window.keptDoc), true);
    await page.locator('#readwrite-choose-writing').click();
    await page.locator('#readwrite-search').fill('第二份');
    await page.locator('#readwrite-picker-list button').click();
    await page.waitForFunction(() => writingState.doc.path === '第二份文稿.md' && !writingState.busy);
    await page.evaluate(() => writingMarkdown.editor.setValue('# 第二份文稿'));
    await page.locator('#readwrite-new-writing').click();
    await page.locator('#writing-name').fill('双栏新建'); await page.locator('#writing-confirm').click();
    await page.waitForFunction(() => writingState.doc.path === '双栏新建.md' && !writingState.busy);
    await page.evaluate(() => writingMarkdown.editor.setValue('# 双栏中新建\n\n自动保存正常。'));
    await page.setViewportSize({width: 1000, height: 720});
    await page.screenshot({path: path.join(output, 'readwrite-narrow.png')});
    const narrow = await page.evaluate(() => ({overflow: document.documentElement.scrollWidth > innerWidth + 1, editor: document.querySelector('.CodeMirror').clientHeight, footer: document.querySelector('.writing-status').getBoundingClientRect().bottom}));
    assert.equal(narrow.overflow, false); assert.ok(narrow.editor > 100 && narrow.footer <= 720, JSON.stringify(narrow));
    await page.locator('#readwrite-only-writing').click();
    await page.waitForFunction(() => !document.querySelector('#reader-dialog').open && writingState.mode === 'writing');
    assert.equal(await page.locator('#writing-view').isVisible(), true);
    // Enter from reading with a draft already open, then verify desktop close saves it.
    await page.locator('#mode-reading').click();
    await page.evaluate(() => openReader('1234567890abcdef'));
    await page.locator('#reader-open-writing').click(); await split();
    await page.evaluate(() => writingMarkdown.editor.setValue('# 关闭前保存'));
    assert.equal(await page.evaluate(() => ezreadPrepareDesktopClose()), true);
    const data = await (await page.request.get(origin + '/api/writing/document?path=' + encodeURIComponent('双栏新建.md'))).json();
    assert.equal(data.content, '# 关闭前保存');
    await page.keyboard.press('Escape');
    await page.waitForFunction(() => !document.querySelector('#reader-dialog').open);
    assert.equal(await page.evaluate(() => document.querySelector('#writing-view').parentElement.matches('main.workspace')), true);
    assert.deepEqual(errors, []);
    console.log('Read/write passed: both entry points, real PDF, editor identity, typing/save, paper/manuscript switches, new manuscript, divider, settings, narrow layout, collapse/restore and desktop-close persistence.');
  } finally { await browser.close(); }
})().catch(error => {console.error(error); process.exitCode = 1;});
